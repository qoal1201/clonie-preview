/// 덩이 하나에서 **뽑아낸 이야기 한 장**. `@Generable` 이라 파싱이 없다 — 스키마가 곧 타입이다.
///
/// ⚠ **연결질문은 여기 없다.** 초안에 질문 칸을 두면 그 질문이 조각과 같이 저장되고,
/// 그때부터 **연결이 두 벌**이 된다 — 하나는 모델이 지어낸 문장, 하나는 임베딩 색인이
/// 실제 볼트에서 찾아낸 이웃(#32·#33). 색인 쪽이 진짜다. 그래서 이 자리는 **글자만** 만든다.
/// ⚠ **여기에 예시 문장을 적지 않는다.** `실측 2026-08-30`: 제목 칸의 안내에
/// 「예: '주문 데이터 30곳 모아 폐기율 20% 감축'」을 두었더니, 이야기가 없는 덩이(연락처 줄)에서
/// 모델이 **그 예시를 그대로 조각으로 뱉었다.** 안내문의 예시는 원문과 구별되지 않는다.
@Generable
struct ExtractedStory {
    /// ★ **저장되지 않는 칸이다** — 모델이 스스로 「이 일이 언제 어디 일인가」를 먼저 답하게 하는 자리다.
    /// 이것이 먼저 서면 같은 때 같은 자리의 일을 두 장으로 쪼갤 때 그 사실이 모델 눈에 보인다.
    /// `실측 2026-08-30`: 이 칸이 없던 판은 한 문항의 답 하나를 원인/행동/결과로 두세 장에 흩었다.
    @Guide(description: "이 일이 언제 어디서 있었나. 원문에 적힌 때와 자리를 짧게 옮긴다")
    var occasion: String

    @Guide(description: "이 사건의 한 줄 제목. 무엇을 해서 무엇이 됐는지를, 원문에 실제로 있는 사실과 숫자로만 쓴다")
    var title: String

    @Guide(description: "2~5문장. 이 사건 하나의 상황 → 행동 → 결과를 한 장에 다 담는다. 원문에 있는 사실과 숫자만 쓴다")
    var body: String
}

/// 모델이 채워 주는 칸 — **목록이다** (#40 2판).
///
/// ★ 1판은 이 자리가 `title`·`body` **단수**였다. 그것이 실전에서 무너진 자리가 여기다
/// (박선호 2026-08-30, 창업대회 지원서: *"그냥 기계적으로 문단을 나누어서"* · **「못 쓸 수준」**):
/// 기계가 먼저 이야기 경계와 무관하게 자르고(문항 번호 없는 글 = 빈 줄 1,200자 덩이) 모델은
/// 그 덩이를 **요약만** 했다. garbage-in 이라 모델을 아무리 좋게 시켜도 안 나아진다.
/// 2판은 순서를 바꾼다 — 기계는 **덩이를 떼어 주기만** 하고(헤딩 → 문항 → 문단),
/// **무엇이 한 이야기인가는 모델이 판정한다.**
///
/// ⚠ **0개가 정상 답이다.** 목차·머리말·연락처 같은 덩이에는 재사용할 이야기가 없고,
/// 그때 억지로 한 장을 만들면 저장소에 쓰레기가 앉는다. **「없다」는 판정 자체가 값이다** —
/// 화면은 그 덩이를 버린다(기계 자르기로 강등하지 않는다).
/// ⚠ **그 판정을 이 호출이 하지 않는다** — 아래 `StoryPresence` 문지기가 먼저 한다.
/// 여기 안내문에 「없으면 빈 목록」을 다시 적으면 회수가 무너진다(그 실측이 문지기 머리글에 있다).
///
/// ★ **상한 3 이 「셋을 채워라」로 읽혔다** (`실측 2026-08-30` 셀프 실기): 대기업 표준 자소서
/// 문항 넷에서 **11장**이 나왔는데, 한 사건이 원인·행동·결과 문장 단위로 두세 장에 흩어졌다
/// (갈등 문항 하나가 「팀원과의 갈등 해결」+「논리적 해결 전략 적용」+「효과적인 의사소통」).
/// 상한은 그대로 두고 **안내문이 기대값을 말한다** — 상한을 내리면 진짜 사건 셋이 든 창에서 하나가
/// 떨어지고, 그건 병합(`SECTION_MIN`)으로 창을 키운 것과 정면으로 부딪친다.
///
/// ★ **세는 칸이 목록 앞에 선다.** `@Generable` 은 칸을 **선언한 순서로** 채우므로, 목록을 짓기
/// 전에 「몇 개인가」를 먼저 답하게 하면 그 수가 목록의 길이를 잡아당긴다. 안내문만으로는 안 됐다
/// (`실측 2026-08-30`: 「보통 1~2장」을 안내문에 적은 판으로 대기업 자소서 3회 = 10·11·9장).
@Generable
struct ExtractedStories {
    @Guide(description: "이 글에 서술된, 때와 자리가 서로 다른 사건이 몇 개인가. 한 사건의 까닭·한 일·결과·배운 점은 전부 하나로 센다. 대개 1이다",
           .range(1...3))
    var eventCount: Int

    @Guide(description: "위에서 센 수만큼. 사건 하나에 한 장", .maximumCount(3))
    var drafts: [ExtractedStory]
}

/// **붙인 창 전용 칸** — 화면이 짧은 구획 여럿을 한 창으로 붙여 보냈을 때만 쓴다 (#40 2판 조정).
///
/// ★ **왜 타입을 따로 두나.** 위 `ExtractedStories` 의 세는 칸이 「대개 1이다」라고 말하는데,
/// 그것이 과분할을 막는 **가장 센 손잡이**다(`실측 2026-08-30`: 이 문구를 빼면 대기업 자소서가
/// 4장 → 8장으로 무너졌다). 그런데 `@Guide` 는 **타입에 박혀 있어 호출마다 못 바꾼다.**
/// 붙인 창에서만 그 문구를 풀려면 타입이 둘이어야 한다.
/// ⚠ **그래서 이 타입이 생긴 것이지, 안내문이 더 좋아서가 아니다.** 붙지 않은 창(`parts == 1`)은
/// 위 타입으로 **글자 하나 안 바뀐 채** 간다 — 그 길의 실측(대기업 4장 3/3)을 안 건드리는 것이
/// 이 갈림의 목적이다.
///
/// ★ **여기엔 세는 칸이 없다** — 있으면 안 되는 것이 아니라 **재 보니 해로웠다.**
/// `실측 2026-08-30`: 위 타입처럼 `eventCount` 를 앞에 세우면 붙인 창에서 그 칸이
/// **3회 전부 1** 이 나왔고(안내문을 「대개 붙인 편 수와 같다」로 바꿔도 1이었다),
/// 목록이 그 수에 묶여 한 편이 통째로 빠졌다. 세는 칸은 **쪼개는 것을 막는 장치**인데
/// 붙인 창에서는 그 일을 **편 경계**가 이미 한다(「한 편에서 두 장을 만들지 않는다」).
/// 그래서 여기서는 세는 칸이 막을 것은 안 막고 회수만 깎았다.
@Generable
struct MergedStories {
    @Guide(description: "편마다 한 장씩. 겪은 일이 있는 편만 넣는다", .maximumCount(3))
    var drafts: [ExtractedStory]
}

/// **문지기** — 이 덩이에 뽑을 것이 있기는 한가 (#40 2판).
///
/// ★ 왜 판정을 따로 부르나 (`실측 2026-08-30`, 이 맥에서 덩이 4개 × 4회씩):
/// 한 번의 호출에 「빠짐없이 뽑아라」와 「없으면 빈 목록」을 같이 넣으면 **둘이 하나의 손잡이**가
/// 된다 — 어느 쪽으로 돌려도 반대쪽이 무너졌다:
/// - 뽑기를 세게: 진짜 덩이 12/12 성공, 그런데 **목차·서류안내에서도 2~3장을 지어냈다**
/// - 빈 목록을 세게: 목차·연락처 12/12 정확히 0장, 그런데 **진짜 덩이도 3~4번 중 2~3번 0장**
/// 손잡이를 **둘로 가른다.** 문지기는 「있나 없나」만 답하고(짧아서 1초 안쪽), 통과한 덩이에서만
/// 뽑기가 돈다 — 그러면 뽑기 쪽은 회수만 신경 쓰면 된다.
@Generable
struct StoryPresence {
    @Guide(description: "면접에서 다시 꺼내 쓸 수 있는 경험·성과·결정이 이 글에 들어 있으면 true")
    var hasStory: Bool
}

/// 원문 한 덩이 → **이야기 0~3장** (#40 2판).
///
/// ⚠ **온디바이스다.** Apple FoundationModels 는 기기 안에서 돈다 — 그래서 면접 모드
/// 판정선(`tests/check_interview_offline.py`)을 그대로 통과한다. 그것이 백엔드(Ollama·
/// OpenAI 등) 대신 이것을 고른 이유다: 자소서는 밖으로 나가면 안 되는 글이다.
///
/// ⚠ **덩이마다 새 세션**이다. 세션 하나의 문맥 창이 4,096 토큰이라 여러 덩이를 한 세션에
/// 이어 붙이면 뒤쪽에서 조용히 창을 넘긴다. 덩이를 떼는 것은 화면이 하고, 여기는
/// 받은 한 덩이만 본다.
enum FragmentDrafter {

    /// 뽑아낸 이야기 한 장 — 브리지로 나가는 모양.
    struct Draft {
        let title: String
        let body: String
    }

    /// 결과 셋 — 화면이 이 셋을 서로 다르게 그린다.
    /// - `ok`: 답이 왔다. **빈 목록도 `ok` 다** — 「이 덩이엔 이야기가 없다」는 사고가 아니라 판정이다
    /// - `unavailable`: **이 기기에서 못 쓴다.** 다시 눌러도 같다 — 사용자가 설정을 고쳐야 한다
    /// - `failed`: 쓸 수는 있는데 이번에 실패했다. 다시 누르면 될 수 있다
    enum Outcome {
        case ok([Draft])
        case unavailable(String)
        case failed(String)
    }

    /// 한 세션에 넣는 글자 상한.
    ///
    /// ★ **1판의 1,500 에서 올렸다** (#40 2판). 계산은 이렇다 — 문맥 창 4,096 토큰을 넷이 나눠 쓴다:
    /// 지시문+스키마 ≈ 300 · **입력** · 출력 ≤ 3장 × (제목 34자 + 본문 4문장 ≈ 200자) ≈ 700자.
    /// 한국어를 **글자당 1.5 토큰**(보수적 상한)으로 잡으면 출력이 ≈ 1,050 토큰이라
    /// 입력에 남는 자리가 ≈ 2,700 토큰 = **약 1,800자**다.
    /// 1,600 은 거기서 한 뼘 물러선 값이고, 화면이 떼어 주는 덩이(`CHUNK_MAX` = 1,400)보다
    /// 넉넉해 **우리 덩이에서는 이 자름이 안 걸린다** — 걸리는 것은 밖에서 더 큰 글이 올 때뿐이다.
    /// 넘치면 **자르고 계속한다**: 통째로 실패하는 것보다 앞부분으로 뽑는 쪽이 낫다.
    /// ⚠ 1.5 토큰/글자는 **선언한 보수값이지 실측이 아니다.** 틀려서 넘치면
    /// `exceededContextWindowSize` 가 오고, 화면이 그 덩이만 기계 자르기로 물러선다.
    ///
    /// ⚠⚠ **위 계산의 「지시문+스키마 ≈ 300」은 이미 틀렸다** (`실측 2026-08-30`, 3판 조정에서 발견).
    /// 실제로 재 보니 지시문만 **기본 642자 · 붙은 창 929자 · 문항 창 1,125자**였다 —
    /// 보수값 1.5 토큰/글자로는 문항 창이 **1,688 토큰**이라 가정의 다섯 배가 넘는다.
    /// 그 판으로 대기업 자소서(창 269자)를 돌렸더니 **6회 중 1회 `exceededContextWindowSize`**
    /// 가 났고 그 회차만 72초가 걸렸다(정상 18초). 지시문을 줄여 되돌렸다.
    /// ⚠ **이 상한은 안 내렸다.** 넘친 것은 입력이 아니라 지시문이라, 여기를 내리면 원인이 아닌
    /// 자리를 조인다 — 화면이 주는 창(`CHUNK_MAX` = 1,400)은 지금도 이 밑이다.
    /// **다시 열 조건 = 지시문이 또 길어질 때.** 그때 재야 하는 것은 이 수가 아니라 지시문 길이다.
    static let inputLimit = 1_600

    /// 한 덩이에서 뽑을 이야기 상한. **스키마의 `.maximumCount` 와 같은 값이어야 한다** —
    /// 갈리면 모델이 넷을 내고 화면이 셋만 받는 조용한 손실이 된다.
    static let maxDrafts = 3

    /// ★ **이야기가 들어갈 수 없는 크기** — 이 밑으로는 모델을 아예 안 부른다 (#40 2판).
    ///
    /// 왜 기계 자가 하나 남았나: 문지기(`StoryPresence`)가 목차·서류안내는 안정적으로 걸러내는데
    /// **표지(문서 제목 + 이름 + 연락처)에서는 흔들린다**(`실측 2026-08-30`: 5회 중 2~3회 통과,
    /// 통과하면 3장을 지어냈다). 문지기를 더 세게 조이면 이번엔 진짜 덩이가 떨어졌다 — 같은 손잡이다.
    /// 그래서 **모델이 못 가르는 자리를 길이가 가른다.** 상황·행동·결과 세 문장이 한국어로
    /// 들어가려면 최소 이 정도는 필요하고, 그 밑의 글은 제목·연락처·목차뿐이다.
    /// `실측 2026-08-30` 이 프로브의 덩이 길이: 표지 64자 · 목차 44자 · 서류안내 78자 ·
    /// **가장 짧은 진짜 이야기 덩이 292자.** 두 무리 사이 간격이 214자라 120은 그 사이다.
    /// ⚠ **실측이 아니라 그 간격 위에 선언한 값이다.** 틀렸을 때의 대가는 짧은 진짜 덩이 하나가
    /// 「이야기 없음」으로 뜨는 것이고, 그 덩이의 원문은 카드에 그대로 남아 있다.
    ///
    /// ★ **그 대가가 실제로 났고, 고친 자리는 여기가 아니다** (`실측 2026-08-30` 셀프 실기):
    /// 헤딩이 촘촘한 창업대회 지원서에서 구획 창이 110·111·123·78자로 잘려 **진짜 이야기 둘이**
    /// 이 바닥에 걸렸다. 바닥을 낮추면 표지·목차가 도로 들어오므로(위 실측) **바닥은 그대로 두고
    /// 화면이 창을 키운다** — `ChatHTML` 의 `SECTION_MIN`(짧은 헤딩 구획 병합). 이 바닥은
    /// **병합이 끝난 창**에 걸린다. 병합해도 못 넘는 외톨이는 여전히 여기서 떨어진다.
    static let storyFloor = 120

    /// 이 기기에서 쓸 수 있나. 못 쓰면 **한국어 한 줄**을 돌려준다 (쓸 수 있으면 `nil`).
    ///
    /// ⚠ 사유를 뭉뚱그리지 않는다 — 셋의 처방이 서로 다르다.
    static func unavailableReason() -> String? {
        switch SystemLanguageModel.default.availability {
        case .available:
            return nil
        case .unavailable(let reason):
            switch reason {
            case .deviceNotEligible:
                return "이 맥은 Apple Intelligence 를 지원하지 않는다 — 초안 생성은 못 쓴다"
            case .appleIntelligenceNotEnabled:
                return "Apple Intelligence 가 꺼져 있다 — 시스템 설정에서 켜라"
            case .modelNotReady:
                return "모델을 아직 내려받는 중이다 — 잠시 뒤에 다시 눌러라"
            @unknown default:
                return "지금은 초안 생성을 쓸 수 없다"
            }
        @unknown default:
            return "지금은 초안 생성을 쓸 수 없다"
        }
    }

    /// 덩이 하나 → 이야기 0~3장. **던지지 않는다** — 실패도 `Outcome` 이다.
    ///
    /// - Parameter parts: 이 창이 **몇 편을 이어 붙인 것인가** (#40 2판 조정). 화면의
    ///   `mergeShortSections` 가 짧은 헤딩 구획을 붙이고 그 수를 브리지 꾸러미에 실어 보낸다.
    ///   ⚠ **기본값 1 이 옛 계약이다** — `parts` 가 안 오면(옛 화면·브라우저 단독) 붙지 않은
    ///     창으로 보고 예전 길로 그대로 간다. 새 통로가 아니라 기존 꾸러미의 칸 하나다.
    ///   ⚠ 1 이하는 1 로 본다. 화면이 셋을 잘못 세도 **더 쪼개지는 쪽으로는 안 기운다.**
    /// - Parameter ask: 이 창이 **면접 문항 하나에 대한 답변**인가 (#40 3판 조정). 화면의
    ///   `sliceIntake` 가 `kind === "q"` 로 아는 사실이고, `parts` 와 **같은 길로** 실려 온다.
    ///   ⚠ 기본값 `false` 가 옛 계약이다 — 안 오면 예전 길로 그대로 간다.
    static func draft(text: String, parts: Int = 1, ask: Bool = false) async -> Outcome {
        if let why = unavailableReason() { return .unavailable(why) }

        // 편 수를 우리 상한 안으로 좁힌다 — 화면이 넷을 세어도 뽑기 상한은 셋이다.
        let parts = min(max(parts, 1), maxDrafts)
        let cleaned = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleaned.isEmpty else { return .failed("빈 글이라 만들 것이 없다") }
        let input = cleaned.count > inputLimit
            ? String(cleaned.prefix(inputLimit))
            : cleaned

        // ★ **⓪ 길이 바닥.** 이야기가 들어갈 수 없는 크기면 모델을 안 부른다 (`storyFloor` 머리글).
        if input.count < storyFloor { return .ok([]) }

        // ★ **① 문지기.** 뽑을 것이 있기는 한가. 왜 갈랐는지는 `StoryPresence` 머리글에 있다.
        //   ⚠ 문지기가 실패하면 **통과시킨다** — 문지기는 쓰레기를 막으려고 있지, 사람의 글을
        //     막으려고 있는 것이 아니다. 실패로 이야기를 잃는 쪽이 더 비싸다.
        do {
            let gate = LanguageModelSession(instructions: """
                너는 글 한 편을 읽고 **겪은 일이 서술돼 있는지**만 판정한다. 판정만 한다 — \
                요약하거나 이야기를 만들지 않는다.
                true = 글쓴이가 한 일 · 그때 있었던 일 · 그 결과나 성과 · 내린 결정과 그 까닭 \
                가운데 무엇이든 **문장으로** 적혀 있다.
                false = 그런 문장이 없다. 아래가 전부 false 다:
                - 이름·연락처·주소·이메일만 적힌 글
                - 목차, 차례, 번호만 붙은 제목 나열
                - 제출 서류 안내, 서식·작성 요령
                - 항목만 나열한 표나 목록
                - 제목 한 줄뿐인 글
                """)
            let verdict = try await gate.respond(
                to: """
                    다음 글에 **글쓴이가 한 일·겪은 일·낸 성과·내린 결정**이 문장으로 서술돼 있나? \
                    제목·연락처·목차·안내문뿐이면 false 다.

                    \(input)
                    """,
                generating: StoryPresence.self)
            if verdict.content.hasStory == false { return .ok([]) }
        } catch let error as LanguageModelSession.GenerationError {
            // 문맥 창을 넘긴 것은 뽑기에서도 넘긴다 — 여기서 끝내는 것이 정직하다.
            if case .exceededContextWindowSize = error { return .failed(message(for: error)) }
        } catch {
            // 통과시킨다 (위 ⚠).
        }

        // ★ **② 뽑기.** 문지기를 지났으니 여기서는 **회수만** 본다 — 「없으면 빈 목록」을
        //   여기 다시 넣으면 손잡이가 도로 하나가 된다(`StoryPresence` 머리글의 실측).
        // ⚠ 지시문과 프롬프트를 가른다. 지시문은 **역할**, 프롬프트는 **이번 글**이다 —
        //   섞으면 원문 안의 명령형 문장이 지시로 읽힌다.
        // ★ 역할이 「요약기」에서 **「추출기」**로 바뀌었다 (2판). 그래서 지시문이 요구하는 것도
        //   바뀐다: *무엇을 줄여라* 가 아니라 *무엇이 한 이야기인지 골라라* 다.
        // ★ **단위가 「이야기」에서 「사건」으로 좁혀졌다** (`실측 2026-08-30` 셀프 실기, 불합격 4건 중 셋).
        //   ① 과분할: 2판의 「이야기 **단위로 갈라서**」가 문장 단위 쪼개기로 읽혔다 — 갈라라는 말이
        //      갈 곳을 안 정해 주면 모델은 문장에서 가른다. 그래서 **가르는 자리를 사건으로 못 박는다.**
        //   ② 중복: 같은 사실이 두 장에 앉았다(해커톤 한 사건이 두 장, 짝 유사도 0.545).
        //      화면의 `dropDupes` 가 그물이지만 **첫 방어선은 여기**다.
        //   ③ 비-이야기·교훈형 제목: 「입사 후 포부」(미래 다짐)가 한 장이 됐고, 제목이
        //      「목표 설정의 중요성」 같은 교훈 문구로 나왔다 — 면접 중에는 제목 한 줄만 보이는데
        //      교훈 문구로는 **어느 사건인지 못 고른다.**
        // ⚠ **여기 「없으면 빈 목록」을 넣지 않는다** (`ExtractedStories` 머리글). 위 ③은 무엇이
        //   한 장이 될 수 **없는지**를 말하지, 아무것도 내지 말라고 말하지 않는다 — 그래서 갈 곳
        //   (사건을 적은 장의 본문 끝)을 같이 준다. 「내지 마라」로 적으면 회수 손잡이가 도로 하나가 된다.
        // ⚠ **못 쓸 제목의 모양만 적고 쓸 제목의 예시는 안 적는다.** 안내문의 예시는 원문과
        //   구별되지 않아 그대로 조각으로 나온다(`ExtractedStory` 머리글의 실측). 「~의 중요성」은
        //   자리표(`~`)가 있어 통째로 베껴질 수 없는 모양이다.
        let session = LanguageModelSession(instructions: instructions(parts: parts, ask: ask))
        do {
            // ⚠ **갈림은 여기 한 자리다.** 붙은 창이면 스키마와 프롬프트가 같이 바뀐다 —
            //   한쪽만 바꾸면 세는 칸의 안내문과 물음이 서로 다른 것을 세라고 말한다.
            // ⚠ **문항 창은 스키마를 안 바꾼다.** 세는 칸의 「대개 1」이 문항 창에도 그대로 맞다 —
            //   문항 하나의 답은 사건 하나다. 바뀌는 것은 개수가 아니라 **본문을 어떻게 적나**라
            //   그건 안내문·물음이 든다(스키마를 또 늘리면 타입이 셋이 되고 셋이 갈린다).
            let told: [ExtractedStory] = parts > 1
                ? try await session.respond(to: mergedPrompt(parts: parts, input: input),
                                            generating: MergedStories.self).content.drafts
                : try await session.respond(to: ask ? askPrompt(input: input) : soloPrompt(input: input),
                                            generating: ExtractedStories.self).content.drafts
            let drafts = told
                .map { Draft(title: $0.title.trimmingCharacters(in: .whitespacesAndNewlines),
                             body: $0.body.trimmingCharacters(in: .whitespacesAndNewlines)) }
                .filter { !($0.title.isEmpty && $0.body.isEmpty) }
                .prefix(maxDrafts)
            return .ok(Array(drafts))
        } catch let error as LanguageModelSession.GenerationError {
            return .failed(message(for: error))
        } catch {
            return .failed("초안을 만들지 못했다")
        }
    }

    // MARK: - 지시문 (`parts` 하나로 갈린다)

    /// ★ **역할과 규칙** — 붙은 창이든 아니든 **한 글자도 안 다르다.**
    /// 갈리는 것은 아래 `countClause` 하나뿐이고, 그것만 갈라 두는 이유는 바로 그것이
    /// 과분할을 막는 손잡이이면서 동시에 붙은 창에서 이야기를 잃게 하는 손잡이이기 때문이다.
    private static let role = """
        너는 면접 준비를 돕는다. 주어진 글에서 **글쓴이가 실제로 겪은 사건**을 골라 \
        사건 하나에 한 장씩 적는다.

        **한 사건은 한 번 있었던 일이다.** 그 일을 하게 된 상황, 그때 한 일, 그 결과, \
        거기서 배운 것 — 이것들은 **한 사건의 부분**이지 각각 다른 사건이 아니다. \
        전부 같은 장의 본문에 넣는다.
        """

    /// 사건을 고르고 적는 규칙. **개수 이야기는 여기 없다** — 그건 `countClause` 가 든다.
    private static let rules = """
        - 장이 둘 이상이면 **각 장의 때와 자리가 서로 달라야 한다.** 같은 때 같은 자리에서 \
        있었던 일이면 그것은 한 장이다. 문장이 여럿인 것은 장을 나눌 까닭이 아니다.
        - 거꾸로, 때와 자리가 **정말 다른** 일이 글 안에 또 있으면 그것은 빠뜨리지 않는다.
        - 앞으로 하겠다는 다짐·포부·목표, 회사에 대한 평가, 일반론은 **사건이 아니다.** \
        그것만으로 한 장을 만들지 않는다.
        - 같은 사실을 두 장에 쓰지 않는다.
        - 제목에는 **그 사건**을 적는다 — 무엇을 해서 무엇이 됐나. 원문에 숫자가 있으면 그 숫자를 \
        넣는다. 「~의 중요성」 「효과적인 ~」 「~하는 자세」처럼 배운 점·태도를 제목으로 삼지 마라. \
        그런 제목으로는 어느 사건인지 알 수 없다.
        - 원문에 있는 사실·숫자만 쓴다. 없는 것을 지어내지 않는다. 한국어로 쓴다.
        """

    /// ★ **여기가 `parts` 가 만지는 유일한 문장이다** (#40 2판 조정).
    ///
    /// `실측 2026-08-30` 셀프 실기가 잰 긴장: 「대개 한 장이다」를 빼면 붙은 창에서 이야기 셋이
    /// 다 나오는데 **문항 창이 4장 → 8장으로 무너지고**, 넣으면 문항 창이 4장으로 굳는 대신
    /// **붙은 창에서 한 편이 통째로 빠졌다.** 같은 손잡이 하나를 양쪽에서 당기고 있었다.
    /// 화면이 「이 창은 몇 편을 붙인 것인가」를 알고 있으므로, **그 수를 받아 손잡이를 둘로 가른다** —
    /// `StoryPresence` 문지기를 뽑기에서 갈랐던 것과 같은 수다.
    ///
    /// ★ **갈래가 셋이 됐다** (#40 3판 조정, `실측 2026-08-30` 현실 장문 자소서). 붙은 창 다음으로
    /// 갈라야 했던 것이 **문항 창**이다: 700~1,000자짜리 문항 답 셋을 3회 돌렸더니 협업 문항이
    /// **3회 중 0회만 온전**했다 — 1회는 개조식으로 무너졌고(「~요구. ~반대. ~정리.」),
    /// 2회는 갈등이 터지는 데서 잘려 **9일 vs 4일이라는 결론 숫자가 통째로 빠졌다.**
    /// 붙은 창과 **정확히 같은 수**로 고친다: 화면만 아는 사실(이 창이 문항 답인가)을 실어 보내고,
    /// 그 창에서만 문구를 바꾼다.
    /// ⚠ **셋이 겹칠 일은 없다.** 문항 창은 `mergeShortSections` 가 절대 안 붙이므로(문항 경계는
    ///   사람이 그은 것) `parts > 1 && ask` 는 화면이 낼 수 없는 짝이다. 그래도 순서를 박아 둔다 —
    ///   못 오는 짝이 오면 **창 모양에 대한 사실**(붙었나)이 이긴다.
    private static func countClause(parts: Int, ask: Bool) -> String {
        if parts > 1 {
            return """
                - 이 글은 **서로 다른 글 \(parts)편을 이어 붙인 것**이다. 편마다 앞에 그 편의 소제목이 있다. \
                **편을 따로따로 읽고, 겪은 일이 있는 편마다 한 장씩** 적는다. 한 편에서 두 장을 만들지 않고, \
                두 편을 한 장에 합치지도 않는다. 겪은 일이 없는 편은 그냥 넘어간다.
                - **직접 알아본 일도 겪은 일이다.** 인터뷰·조사·관찰·실험처럼 글쓴이나 그 팀이 **한 행동**과 \
                거기서 **알게 된 것**이 적혀 있으면, 그 편이 문제를 설명하는 모양이어도 사건이 있는 것이다.
                - 거꾸로 **앞으로 하겠다는 계획·목표만 적힌 편은 넘어간다.** 아직 안 한 일은 겪은 일이 아니다.
                """
        }
        if ask {
            // ⚠ **짧게 쓴다.** 이 문단은 문맥 창을 먹는다 — 아래 `instructions` 머리글의 실측.
            return """
                - 이 글은 **면접 문항 하나에 대한 답변**이다. 대개 사건 하나를 말한다 — **답은 대개 한 장이다.**
                - 답변이 **여러 문단이어도 한 사건**이다. 갈등이 난 문단·그것을 푼 문단·결과 문단은 \
                같은 일의 앞뒤라, **문단마다 한 장을 만들지 말고 한 장의 본문에 이어서** 적는다.
                - 끝에 붙은 **다짐·포부 문단**(「~가 되겠습니다」)은 뺀다. 그 사건에서 배운 것은 남긴다.
                - 본문은 **원문 문장을 살려 결과까지 끝까지** 쓴다. 개조식(「~함」 「~요구.」)으로 줄이지 말고 \
                **원문의 숫자를 하나도 빠뜨리지 마라.**
                """
        }
        return "- 글 하나는 대개 사건 하나를 말한다. **그러면 답은 한 장이다.**"
    }

    /// 지시문 한 벌. ⚠ `parts == 1 && !ask` 면 2판 조정 직후의 글자와 **완전히 같다.**
    static func instructions(parts: Int, ask: Bool = false) -> String {
        "\(role)\n\n\(countClause(parts: parts, ask: ask))\n\(rules)"
    }

    /// 붙지 않은 창의 물음. **개수 기대값을 여기서 한 번 더 말한다** — 지시문과 물음 양쪽에
    /// 서 있어야 문항 창이 4장에서 안 흔들렸다(`실측 2026-08-30`).
    static func soloPrompt(input: String) -> String {
        """
        다음 글은 사건을 몇 개 말하고 있나? 그 수만큼 장을 적어라. **대개 한 장이다.**

        \(input)
        """
    }

    /// 문항 창의 물음. **개수는 `soloPrompt` 와 같은 기대값**이고(문항 하나 = 대개 사건 하나),
    /// 더해진 것은 **어떻게 적나**다 — 잘림과 개조식이 이 자리에서 났다(`countClause` 머리글의 실측).
    static func askPrompt(input: String) -> String {
        """
        다음은 면접 문항 하나에 대한 답변이다. **대개 한 장**으로, 원문 문장을 살려 \
        상황부터 결과까지 끝까지 적어라.

        \(input)
        """
    }

    /// 붙은 창의 물음. 세는 단위가 **사건이 아니라 편**이다 — `MergedStories` 의 세는 칸과 같은 말.
    static func mergedPrompt(parts: Int, input: String) -> String {
        """
        다음 글에는 소제목으로 갈린 글 \(parts)편이 이어 붙어 있다. \
        **편마다** 겪은 일이 서술돼 있는지 보고, 있는 편마다 한 장씩 적어라.

        \(input)
        """
    }

    /// 생성 사고를 **사용자가 읽을 한 줄**로. 개발자용 원문은 stderr 이 든다.
    static func message(for error: LanguageModelSession.GenerationError) -> String {
        switch error {
        case .exceededContextWindowSize:
            return "글이 너무 길다 — 더 짧게 잘라서 다시 눌러라"
        case .guardrailViolation:
            return "모델이 이 글을 다루기를 거부했다"
        case .refusal:
            return "모델이 이 글로 초안 만들기를 거부했다"
        case .unsupportedLanguageOrLocale:
            return "이 언어는 아직 못 다룬다"
        case .assetsUnavailable:
            return "모델 파일이 준비되지 않았다 — 잠시 뒤에 다시 눌러라"
        case .rateLimited, .concurrentRequests:
            return "요청이 몰렸다 — 잠시 뒤에 다시 눌러라"
        case .decodingFailure, .unsupportedGuide:
            return "모델이 낸 답을 우리 모양으로 못 읽었다"
        @unknown default:
            return "초안을 만들지 못했다"
        }
    }
}

/// 모델이 돌려주는 **정돈된 질문 한 줄**.
@Generable
struct TidiedQuestion {
    @Guide(description: "정돈된 면접 질문 한 문장. 원문의 뜻만 담고 새 내용을 더하지 않는다")
    var text: String
}

/// **문지기** — 이게 질문이긴 한가 (#47 후속).
///
/// ★ 왜 정돈 앞에 이것이 서나 (`실측 2026-08-31`, #52 채증 ④ · #37 코멘트 발견 3):
/// 실전 볼트의 `fromInterview` 질문 **5건이 전부 전사 쓰레기**였다 — 인사말
/// (「네 어서오세요 반갑습니다 자리에 앉아주시기 바랍니다」) · 오인식(「직문」) ·
/// 문장 중간 잘림(「라는 결과를 얻을 거라고 저는 확신 변을…」). 준비도 줄의 빨강 9 중 5 가 이것이다.
/// **정돈(`QuestionTidier`)은 그것을 못 막는다** — 다듬는 일만 하므로 인사말을 넣으면
/// **다듬어진 인사말**이 나온다. 「이게 질문이긴 한가」는 다른 물음이라 다른 손잡이가 든다
/// (`StoryPresence` 가 뽑기에서 갈라져 나온 것과 **같은 수**다).
///
/// ⚠ **화면의 `askable` 과 다른 자다.** 그쪽은 기계 자(길이·맞장구 목록)로 면접 **중에**
/// 재조준을 걸러내고, 이쪽은 모델 자로 면접이 **끝난 뒤** 목록에 앉을 것을 거른다.
/// 인사말 한 줄은 길어서 기계 자를 그냥 통과한다 — 위 실측이 그 증거다.
///
/// ⚠ **여기에 진짜 질문의 예시를 적지 않는다** (`ExtractedStory` 머리글의 실측). 나가는 칸이
/// `Bool` 하나라 예시가 그대로 출력될 자리는 없지만, 예시 한 줄은 판정을 그 한 줄 쪽으로 끌어당긴다.
/// **못 되는 것의 모양만** 적는다.
@Generable
struct AskedQuestion {
    @Guide(description: "면접관이 지원자에게 답을 요구하며 던진 질문이면 true")
    var asked: Bool
}

/// 들린 대로 받아적힌 면접 질문 → **자연스러운 표준 문장 하나** (#47).
///
/// ★ 왜 필요한가 (박선호 2026-08-30, 실전 재실기):
/// *"마이크에서 인식한 약간 발음이 뭉개지거나 문장 완성 상태가 안좋은 그대로 색인을 보여주는게
/// 너무 어설픔"*. 면접에서 수확한 질문(#22 → #35)이 전사 원문 그대로 구멍 목록·색인에 앉는다.
///
/// ⚠ **면접 중에는 안 돈다.** 정돈은 면접이 끝나고 **쌓기로 돌아온 뒤**에 일어난다 —
/// 화면 쪽에서 `stackRender` 아래(판정선 검사의 선언된 경계 밖)에서만 통로를 연다.
/// 온디바이스라 네트워크 판정선과는 무관하지만, **면접 중에 모델을 물고 있을 이유가 없다.**
///
/// ⚠ **뜻이 불명확하면 원문 그대로 돌려준다.** 못 알아들은 질문을 그럴듯하게 지어내면
/// 색인이 **없던 질문**을 갖게 되고, 그건 어설픈 원문보다 나쁘다.
///
/// ★ **앞에 문지기가 하나 섰다** (#47 후속): `AskedQuestion` 이 「이게 질문이긴 한가」를 먼저
/// 판정하고, 아니면 정돈을 아예 안 돈다(`.junk`). 정돈은 다듬는 일만 해서 **인사말을 넣으면
/// 다듬어진 인사말이 나온다** — 다른 물음이라 손잡이를 갈랐다(`StoryPresence` 와 같은 수).
enum QuestionTidier {

    /// 정돈에 넣는 글자 상한. 질문 한 줄이라 문맥 창이 문제가 될 일이 없다 —
    /// 이건 전사 사고(같은 어절이 수백 번 반복되는 것)로 문맥 창을 넘기지 않으려는 자물쇠다.
    static let inputLimit = 400

    /// 결과 **넷** — `FragmentDrafter.Outcome` 과 **모양은 비슷하고 짐이 다르다**(목록이 아니라 한 줄).
    /// 저쪽 타입을 빌려 쓰면 질문 한 줄이 `Draft.title` 에 실려 다니게 되고, 그 자리에서
    /// 「조각인가 질문인가」가 흐려진다.
    ///
    /// ★ `junk` 가 #47 후속으로 늘었다 — **문지기의 판정이지 사고가 아니다.** 그래서 `failed`
    /// 와 한 칸에 접으면 안 된다: 화면이 `failed` 를 「원문 유지」로 읽는데, 여기서 접으면
    /// **버려야 할 것이 그대로 남는다.**
    enum Outcome {
        case ok(String)
        /// 질문이 아니다 — 목록에 안 앉힌다. 다시 눌러도 같다.
        case junk
        case unavailable(String)
        case failed(String)
    }

    /// 이 기기에서 쓸 수 있나. **`FragmentDrafter` 와 같은 자를 쓴다** — 자를 두 벌 두면 갈린다.
    static func unavailableReason() -> String? { FragmentDrafter.unavailableReason() }

    /// 질문 한 줄 → 정돈된 한 줄. **던지지 않는다.**
    static func tidy(text: String) async -> Outcome {
        if let why = unavailableReason() { return .unavailable(why) }
        let cleaned = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleaned.isEmpty else { return .failed("빈 글이라 정돈할 것이 없다") }
        let input = cleaned.count > inputLimit ? String(cleaned.prefix(inputLimit)) : cleaned

        // ★ **① 문지기.** 이게 질문이긴 한가 (`AskedQuestion` 머리글). 다듬기 앞에 세운다 —
        //   인사말을 다듬으면 **다듬어진 인사말**이 나올 뿐이다.
        // ⚠ **사고 나면 통과시킨다.** 왜 여기서 `judgeHarvest` 의 규칙(*잘못 줍는 것이 못 줍는
        //   것보다 비싸다*)을 그대로 안 쓰나 — 그 규칙이 비쌌던 까닭이 #53 에서 걷혔기 때문이다.
        //   그 규칙은 **되먹임**을 두고 한 말이었다: 잘못 주운 질문 글자가 색인의 열쇠로 들어가
        //   면접을 할수록 검색이 나빠졌다(#52 채증 ④). #53 이 그 열쇠를 끊어서, 지금 잘못 주운
        //   것의 대가는 **목록에 한 줄 보이는 것**이고 그 줄에는 ✕ 가 붙어 있다 — 사람이 1회로
        //   되돌린다. 거꾸로 사고로 버리면 **면접에서 실제로 나온 질문이 조용히 사라지고**,
        //   그건 그 면접을 다시 하지 않는 한 안 돌아온다. 되돌릴 수 있는 쪽으로 기운다.
        //   ⚠ 이건 `false` **판정**에는 안 걸린다 — 판정은 이 문지기가 사려고 만든 것이다.
        do {
            let gate = LanguageModelSession(instructions: gateInstructions)
            let verdict = try await gate.respond(to: gatePrompt(input: input),
                                                 generating: AskedQuestion.self)
            if verdict.content.asked == false { return .junk }
        } catch let error as LanguageModelSession.GenerationError {
            // 문맥 창을 넘긴 것은 정돈에서도 넘긴다 — 여기서 끝내는 것이 정직하다.
            if case .exceededContextWindowSize = error {
                return .failed(FragmentDrafter.message(for: error))
            }
            // 나머지는 통과시킨다 (위 ⚠).
        } catch {
            // 통과시킨다 (위 ⚠).
        }

        // ★ **② 정돈.** 문지기를 지났으니 여기서는 **문장만** 본다.
        let session = LanguageModelSession(instructions: """
            너는 음성 인식으로 받아적힌 면접 질문을 정돈한다. 들린 대로 적혀 발음이 뭉개졌거나 \
            문장이 끝나지 않은 한 줄을, **자연스러운 표준 한국어 질문 한 문장**으로 고친다.
            규칙:
            - 「어」 「그」 「아」 「저기」 「그러면은」 같은 군말과 겹쳐 들린 말을 걷어낸다.
            - 새 내용을 더하지 않는다. 원문에 없는 조건·대상·수치를 넣지 않는다.
            - **질문이 가리키는 대상은 지우지 않는다** — 「저희 회사에」 「팀에서」 처럼 \
            무엇에 대한 질문인지 정하는 말은 그대로 남긴다.
            - 존댓말 의문문 한 문장으로, 물음표로 끝낸다.
            - 뜻이 불명확하면 **원문을 그대로 돌려준다.** 그럴듯하게 지어내지 않는다.
            """)
        do {
            let response = try await session.respond(
                to: "다음 질문을 정돈해라:\n\n\(input)",
                generating: TidiedQuestion.self)
            let t = response.content.text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !t.isEmpty else { return .failed("모델이 빈 줄을 냈다") }
            // ⚠ **여기서 「믿을 만한가」를 판정하지 않는다.** 원문과 견주는 자(`tidyOk`)는
            //   화면에 있다 — 원문을 들고 있는 것이 화면이고, 자가 두 곳이면 갈린다.
            return .ok(t)
        } catch let error as LanguageModelSession.GenerationError {
            return .failed(FragmentDrafter.message(for: error))
        } catch {
            return .failed("질문을 정돈하지 못했다")
        }
    }

    // MARK: - 문지기의 말 (#47 후속)

    /// 문지기 지시문 — **역할**이다. 이번 줄은 아래 `gatePrompt` 가 든다.
    ///
    /// ⚠ **거짓 쪽의 모양만 적는다.** 진짜 질문의 예시를 적으면 판정이 그 한 줄을 닮은 쪽으로
    /// 기운다(`AskedQuestion` 머리글). 아래 목록의 괄호 안은 **면접에서 실제로 들린 말**이고
    /// (`실측 2026-08-31`, #52 채증 ④), 나가는 칸이 `Bool` 하나라 이것이 출력으로 샐 자리는 없다.
    /// ⚠ **「물음표가 없어도」·「끝이 잘렸어도」를 뺄 수 없다.** 전사는 물음표를 거의 안 찍고
    /// 문장 끝을 자주 자른다 — 그 둘로 거르면 진짜 질문이 통째로 떨어진다. 문지기가 보는 것은
    /// 문장의 성함이 아니라 **답을 요구하는가**이고, 문장을 펴는 일은 다음 칸(정돈)이 한다.
    static let gateInstructions = """
        너는 면접 녹취에서 주워온 한 줄을 읽고 **그것이 면접관이 지원자에게 던진 질문인지**만 \
        판정한다. 판정만 한다 — 고치거나 다듬거나 새로 쓰지 않는다.
        true = 면접관이 지원자에게 **답을 요구한** 물음이다. 물음표가 없어도, 끝이 잘려 있어도, \
        발음이 뭉개져 받아적혔어도, 답을 요구하는 물음이면 true 다.
        false = 그런 물음이 아니다. 아래가 전부 false 다:
        - 인사말·맞이하는 말 (「반갑습니다」 「어서 오세요」)
        - 면접 진행 안내 (「자리에 앉아주시기 바랍니다」 「지금부터 면접을 시작하겠습니다」 \
        「시간이 다 됐습니다」)
        - 지원자 본인이 한 말 — 자기소개·답변·「감사합니다」
        - 면접관의 맞장구·평 (「네」 「그렇군요」 「알겠습니다」)
        - 문장이 아닌 파편 — 어절 몇 개만 남아 **무엇을 묻는지 알 수 없는** 줄, \
        말이 도중에 시작하거나 끊겨 물음인지조차 알 수 없는 줄
        """

    /// 이번 줄. **지시문과 가른다** — 섞으면 줄 안의 명령형이 지시로 읽힌다.
    static func gatePrompt(input: String) -> String {
        """
        다음 한 줄은 면접 녹취에서 주워온 것이다. 면접관이 지원자에게 \
        **답을 요구하며 던진 질문**인가? 인사말·진행 안내·지원자 본인의 말·무엇을 묻는지 \
        알 수 없는 파편이면 false 다.

        \(input)
        """
    }
}
