        raw.map { id, title, body in
            let t = Date(timeIntervalSince1970: 1_750_000_000)
            return Fragment(id: id, title: title, body: body, questionIds: [],
                            createdAt: t, updatedAt: t)
        }
    }

    static func fragment(_ id: String) -> Fragment {
        fragments().first { $0.id == id }!
    }

