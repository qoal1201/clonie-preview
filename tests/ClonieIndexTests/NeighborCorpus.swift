///   중복이라고 부르면 그 알림은 쓸모가 없다. 쉬운 음성만 모으면 간격이 거짓으로 벌어진다.
///
/// ⚠ **말뭉치를 줄여서 초록을 만들지 못하게** 케이스 수 하한이 시험 쪽에 있다.
